
-- CONFIGURAÇÃO COMPLETA DO SITE DO CORRETOR
-- Execute no Supabase em SQL Editor > New query > Run.

create table if not exists site_config (
  id bigint primary key default 1,
  nome_corretor text,
  creci text,
  whatsapp text,
  logo_texto text default 'RA',
  logo_url text,
  banner_url text,
  titulo_principal text,
  subtitulo_principal text,
  texto_contato text,
  updated_at timestamp with time zone default now()
);

create table if not exists imoveis (
  id bigint generated by default as identity primary key,
  titulo text,
  localizacao text,
  descricao text,
  preco text,
  detalhes text,
  imagem_url text,
  destaque text,
  ativo boolean default true,
  tipo text,
  area_m2 numeric,
  quartos integer,
  banheiros integer,
  vagas integer,
  codigo text,
  status text default 'Venda',
  created_at timestamp with time zone default now()
);

create table if not exists mensagens_contato (
  id bigint generated by default as identity primary key,
  nome text,
  whatsapp text,
  interesse text,
  mensagem text,
  created_at timestamp with time zone default now()
);

